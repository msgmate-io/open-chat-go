#!/usr/bin/env python3
"""Generate the integration source-repository registry.

Writes ``backend/integrations/externalintegrations/sources_gen.go`` from the
public and private integration lockfiles so the ``/integrations`` overview can
deep-link API routes, models and functions back to the integration repository
that implements them.

The lockfiles live outside the Go module and are not shipped to the runtime
image, so the mapping is compiled into the binary instead of read at runtime.
The generated file is gitignored: private repository URLs and pins must never
land in the public tree.

The step is best-effort and idempotent: a missing lockfile simply drops the
affected integrations, and the file is only rewritten when its content changes
(so it never triggers a rebuild loop in the dev watcher).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict

LOCK_PATHS = (
    "integrations.lock.json",
    "development/ci/openchat/integrations.private.lock.json",
    ".integrations/private/integrations.private.lock.json",
)

OUTPUT_REL = "backend/integrations/externalintegrations/sources_gen.go"


def repo_root() -> Path:
    # This file lives at <root>/backend/scripts/generate_integration_source_registry.py.
    return Path(__file__).resolve().parents[2]


def load_lock_entries(path: Path) -> Dict[str, dict]:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    entries = raw.get("integrations")
    if not isinstance(entries, dict):
        return {}
    return {str(name): entry for name, entry in entries.items() if isinstance(entry, dict)}


def go_string(value: str) -> str:
    # json.dumps produces a double-quoted literal whose escapes are all valid Go.
    return json.dumps(value)


def render(entries: Dict[str, dict]) -> str:
    lines = [
        "// Code generated by backend/scripts/generate_integration_source_registry.py. DO NOT EDIT.",
        "",
        "package externalintegrations",
        "",
    ]
    rows = []
    for integ_id in sorted(entries):
        entry = entries[integ_id]
        repo = str(entry.get("repo") or "").strip()
        if not repo:
            continue
        ref = str(entry.get("ref") or "main").strip() or "main"
        rows.append((integ_id, repo, ref))

    if rows:
        lines.append("func init() {")
        for integ_id, repo, ref in rows:
            lines.append(f"\tSourceRepositories[{go_string(integ_id)}] = SourceRepository{{")
            lines.append(f"\t\tID:         {go_string(integ_id)},")
            lines.append(f"\t\tRepository: {go_string(repo)},")
            lines.append(f"\t\tRef:        {go_string(ref)},")
            lines.append("\t}")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    root = repo_root()
    merged: Dict[str, dict] = {}
    for rel in LOCK_PATHS:
        path = root / rel
        if path.is_file():
            merged.update(load_lock_entries(path))

    output = root / OUTPUT_REL
    content = render(merged)
    if output.is_file() and output.read_text(encoding="utf-8") == content:
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"[source-registry] wrote {output.relative_to(root)} ({len(merged)} integrations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
